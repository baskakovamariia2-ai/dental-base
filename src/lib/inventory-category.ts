import type { InventoryCategory } from "@prisma/client";

// Автоматическое определение категории по названию.
// Порядок важен: «матрицедержатель» — инструмент, а «матрица» — расходник.
const RULES: [InventoryCategory, RegExp][] = [
  ["ANESTHESIA", /анест|анаст|артикаин|ультракаин|убистезин|септанест|скандонест|мепивака|лидокаин|карпул/i],
  [
    "INSTRUMENTS",
    /бор(?![а-я]*щ)|бор[ыа]?\b|файл|эндоча|наконечник|насадк|зеркал|зонд|пинцет|экскаватор|гладилк|штопфер|кюрет|щипц|элеватор|ромашк|полир|диск|инструмент|линдеман|матрицедерж|кламп|лампа|ультразвук|скалер|протейпер|protaper|reciproc|апекслокатор|эндомотор|коробка\s+эндо|эндо\s*бокс|бокс/i,
  ],
  [
    "MATERIALS",
    /композит|filtek|фильтек|estelite|эстелайт|харизм|charisma|гуттаперч|силер|пломбир|адгезив|бонд|протрав|цемент|паст[аы]?\b|гидроокис|кальци|материал|ирригант|гипохлорит|edta|эдта|хлоргексид|^\s*(композит\s*)?[a-e]\d(\.\d)?\s*$|\b[a-eд][1-4]\b/i,
  ],
  [
    "CONSUMABLES",
    /ватн|палочк|валик|салфет|платк|коффердам|штрипс|брашик|микробраш|аппликатор|абсорбер|обсорбер|штифт|матриц|клин(ья|ыш|ья)?\b|слюноотсос|стакан|перчат|маск|шапоч|бахил|нагрудник|пакет|крафт|палетк|вазелин|спирт|дезинф|маркер|бумаг|пленк|плёнк|шприц|игл|канюл/i,
  ],
];

export function guessCategory(name: string): InventoryCategory {
  for (const [cat, re] of RULES) if (re.test(name)) return cat;
  return "OTHER";
}
